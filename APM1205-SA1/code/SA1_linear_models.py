# 21A. Computational Demonstration on a 10-Observation Subset
# We must select 10 hours where all 5 predictors exhibit variation.
# To avoid a singular matrix, we explicitly include hours with non-zero rainfall.
# Let's find some index positions with rain from the dataset.
rainy_indices = df[df["Rainfall"] > 0].index.tolist()
clear_indices = df[df["Rainfall"] == 0].index.tolist()

# Select a mixture of rainy and non-rainy hours
subset_indices = rainy_indices[:3] + clear_indices[:7]
df_sub = df.iloc[subset_indices].copy()

predictors_f = ["Temperature", "Humidity", "Wind_Speed", "Solar_Radiation", "Rainfall"]
y_sub = df_sub["Bike_Count"].values.reshape(-1, 1)
X_sub = np.column_stack([np.ones(len(df_sub)), df_sub[predictors_f].values])

# Step-by-step Matrix Algebra on the 10-row subset
XtX_sub = X_sub.T @ X_sub
XtX_inv_sub = np.linalg.inv(XtX_sub)
Xty_sub = X_sub.T @ y_sub
beta_hat_sub = XtX_inv_sub @ Xty_sub

# Fit OLS via statsmodels on the same 10-row subset for verification
ols_sub = smf.ols(mlr_formula, data=df_sub).fit()

print("--- 21A. Subset Demonstration (n = 10 observations, p = 6 parameters) ---")
print("Design Matrix X (10 x 6):\n", np.round(X_sub, 2))
print("\nResponse Vector y (10 x 1):\n", y_sub.flatten())
print("\nCross-Product Matrix (X^T X) (6 x 6):\n", np.round(XtX_sub, 2))
print("\nInverse Matrix (X^T X)^(-1) (6 x 6):\n", np.round(XtX_inv_sub, 6))
print("\nCross-Product Vector (X^T y) (6 x 1):\n", np.round(Xty_sub.flatten(), 2))

sub_verify_df = pd.DataFrame({
    "Parameter": ["Intercept"] + predictors_f,
    "Matrix_Formula_Beta_Hat": beta_hat_sub.flatten(),
    "Statsmodels_OLS_Beta_Hat": ols_sub.params.values,
    "Absolute_Difference": np.abs(beta_hat_sub.flatten() - ols_sub.params.values)
})
print("\n--- Subset Verification: Matrix Algebra vs. statsmodels OLS ---")
print(sub_verify_df.to_string(index=False))

# 21B & 22. Full Dataset (n = 8,760) Matrix Verification of Beta_hat AND Standard Errors
y_full = df["Bike_Count"].values.reshape(-1, 1)
X_full = np.column_stack([np.ones(len(df)), df[predictors_f].values])

XtX_full = X_full.T @ X_full
XtX_inv_full = np.linalg.inv(XtX_full)
Xty_full = X_full.T @ y_full
beta_hat_full = XtX_inv_full @ Xty_full

# Compute residuals, MSE (s_e^2), and Variance-Covariance Matrix s_e^2 * (X^T X)^(-1)
y_hat_full = X_full @ beta_hat_full
residuals_full = y_full - y_hat_full
n_obs, p_params = X_full.shape
mse_full = float((residuals_full.T @ residuals_full).item() / (n_obs - p_params))
cov_beta_full = mse_full * XtX_inv_full
se_beta_full = np.sqrt(np.diag(cov_beta_full))

full_matrix_verify = pd.DataFrame({
    "Parameter": ["Intercept"] + predictors_f,
    "Matrix_Beta_Hat": beta_hat_full.flatten(),
    "Software_Beta_Hat": mlr_model.params.values,
    "Matrix_SE": se_beta_full,
    "Software_SE": mlr_model.bse.values,
    "Max_Diff": np.abs(beta_hat_full.flatten() - mlr_model.params.values)
})

print("\n--- 22. Full Dataset (n = 8,760) Matrix vs. Software Output Verification ---")
print(full_matrix_verify.to_string(index=False))
full_matrix_verify.round(6).to_csv("output/tables/partF_matrix_verification.csv", index=False)

